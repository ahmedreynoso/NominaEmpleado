public class Nomina {

    private int clave;
    private String nombre;
    private float horasTrabajadas;
    private float pagoPorHora;

    public Nomina(int clave, String nombre, float horasTrabajadas, float pagoPorHora) {
        this.clave = clave;
        this.nombre = nombre;
        this.horasTrabajadas = horasTrabajadas;
        this.pagoPorHora = pagoPorHora;
    }
}
